#pragma once
#include <string>

// Абстрактный интерфейс — «контракт» для всех людей в школе.
// Нельзя создать объект IPerson напрямую, только через наследников.
class IPerson {
public:
    // Чистая виртуальная функция — вывести информацию об объекте.
    // Каждый наследник обязан её реализовать.
    virtual void printInfo() const = 0;

    // Чистая виртуальная функция — вернуть роль человека ("Ученик", "Аспирант" и т.д.)
    virtual std::string getRole() const = 0;

    // Виртуальный деструктор обязателен, чтобы при delete через указатель
    // на базовый класс вызывался деструктор производного класса.
    virtual ~IPerson() = default;
};
